<?php

declare(strict_types=1);

use Rector\Config\RectorConfig;
use Rector\Php80\Rector\Class_\ClassPropertyAssignToConstructorPromotionRector;
use Rector\TypeDeclaration\Rector\StmtsAwareInterface\SafeDeclareStrictTypesRector;

return RectorConfig::configure()
    ->withPaths([
        __DIR__ . '/src',
        __DIR__ . '/tests',
    ])
    // Matches "php": ">=8.2" in composer.json; never suggests syntax newer than that.
    ->withPhpSets(php82: true)
    ->withPreparedSets(
        deadCode: true,
        codeQuality: true,
        typeDeclarations: true,
        earlyReturn: true,
    )
    ->withImportNames(importShortClasses: false, removeUnusedImports: true)
    ->withSkip([
        // Generated by Codeception and by the test app's Twig cache.
        __DIR__ . '/tests/_support/_generated',
        __DIR__ . '/tests/_craft/storage',
        __DIR__ . '/tests/_output',
        // Craft's guidelines prefix private properties with `_`; a promoted
        // property would put that prefix on the constructor's named arguments.
        ClassPropertyAssignToConstructorPromotionRector::class,
        // Craft core doesn't declare strict types; the plugin follows suit.
        SafeDeclareStrictTypesRector::class,
    ]);
